'use strict'
const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('skinned', {
  ready: (id, cols, rows) => ipcRenderer.send('pty:ready', id, cols, rows),
  input: (id, d) => ipcRenderer.send('pty:input', id, d),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  onData: fn => ipcRenderer.on('pty:data', (_e, id, d) => fn(id, d)),
  onScreenAsk: fn => ipcRenderer.on('screen:ask', (_e, id, n) => fn(id, n)),
  screen: (n, text) => ipcRenderer.send('screen:text', n, text),
  tabs: () => ipcRenderer.invoke('tabs:get'),
  onTabs: fn => ipcRenderer.on('tabs', (_e, s) => fn(s)),
  newTab: () => ipcRenderer.send('tab:new'),
  closeTab: id => ipcRenderer.send('tab:close', id),
  activateTab: id => ipcRenderer.send('tab:activate', id),
  stepTab: d => ipcRenderer.send('tab:step', d),
  moveTab: (id, index) => ipcRenderer.send('tab:move', id, index),
  tabsMenu: () => ipcRenderer.invoke('tabs:menu'),
  sessions: () => ipcRenderer.invoke('sessions:list'),
  openSession: key => ipcRenderer.invoke('sessions:open', key),
  openDashboard: () => ipcRenderer.send('dashboard:open'),
  onDashboard: fn => ipcRenderer.on('dashboard', (_e, id, d) => fn(id, d)),
  reopenTab: () => ipcRenderer.send('tab:reopen'),
  duplicateTab: () => ipcRenderer.send('tab:duplicate'),
  chooser: () => ipcRenderer.invoke('chooser:get'),
  chooserOpen: pick => ipcRenderer.invoke('chooser:open', pick),
  chooserForget: (agent, dir) => ipcRenderer.invoke('chooser:forget', agent, dir),
  chooserProfile: () => ipcRenderer.invoke('chooser:profile'),
  chooserFolder: typed => ipcRenderer.invoke('chooser:folder', typed),
  onHouse: fn => ipcRenderer.on('house', (_e, h) => fn(h)),
  onStrip: fn => ipcRenderer.on('strip', (_e, s) => fn(s)),
  onMetrics: fn => ipcRenderer.on('metrics', (_e, m) => fn(m)),
  onSkin: fn => ipcRenderer.on('skin:load', (_e, s) => fn(s)),
  listSkins: () => ipcRenderer.invoke('skins:list'),
  selectSkin: id => ipcRenderer.invoke('skin:select', id),
  openSkin: () => ipcRenderer.invoke('skin:open'),
  housekeeping: () => ipcRenderer.invoke('house:get'),
  problemsSeen: () => ipcRenderer.send('house:seen'),
  forgetSkin: () => ipcRenderer.invoke('house:forget'),
  openLogs: () => ipcRenderer.send('house:logs'),
  clearLogs: () => ipcRenderer.invoke('house:clear'),
  vizState: () => ipcRenderer.invoke('viz:state'),
  toggleViz: () => ipcRenderer.send('viz:toggle'),
  selectViz: id => ipcRenderer.invoke('viz:select', id),
  soundMuted: () => ipcRenderer.invoke('sound:state'),
  toggleSound: () => ipcRenderer.send('sound:toggle'),
  onSoundMuted: fn => ipcRenderer.on('sound:muted', (_e, m) => fn(m)),
  clipWrite: (text, type) => ipcRenderer.send('clip:write', { text, type }),
  clipRead: () => ipcRenderer.invoke('clip:read'),
  openLink: url => ipcRenderer.send('open-link', url),
  pathForFile: file => webUtils.getPathForFile(file)
})
