'use strict'
// The Carbon mode's data (decision 0015, issue #144): a slim copy of
// docs/research/carbon-atom-data.json, written as app/viz/carbon-data.js,
// a page script that also loads under node. Every level, every line,
// the Rydberg ladder, the outer-electron model and the Bunge 1993 RHF
// basis, with the fields the mode draws from and nothing else. All 559
// lines are kept, so the branching ratios stay NIST's without a
// renormalization.
//   node scripts/research/carbon_slim.js          write the file
//   node scripts/research/carbon_slim.js --check  exit 1 if it differs
// test/viz-carbon.test.js runs build() and compares it with the file.
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..', '..')
const SRC = path.join(ROOT, 'docs', 'research', 'carbon-atom-data.json')
const OUT = path.join(ROOT, 'app', 'viz', 'carbon-data.js')

// A level's outer-electron term key, as outer_electron.terms names it.
const termKey = (conf, term) => conf + ' ' + term

function build (full) {
  const levels = full.levels.map(l => ({
    id: l.id,
    conf: l.conf,
    term: l.term,
    J: Number(l.J),
    g: l.g,
    parity: l.parity,
    E: l.energy_cm,
    eV: l.energy_eV,
    tau: l.tau_s
  }))
  const index = new Map(levels.map((l, i) => [l.id, i]))
  const lines = full.lines.map(l => ({
    u: index.get(l.upper),
    l: index.get(l.lower),
    vac: l.wl_vac_ritz_nm,
    air: l.wl_air_ritz_nm,
    A: l.A_s,
    f: l.f_ik,
    branch: l.branch,
    type: l.type,
    band: l.band,
    acc: l.acc,
    rgb: l.rgb || null
  }))
  const outer = {}
  for (const t of full.outer_electron.terms) outer[termKey(t.conf, t.term)] = { n: t.n, l: t.l, nStar: t.n_star, nr: t.n_r, lambda: t.lambda, meanR: t.mean_r_bohr }
  const rhf = full.orbitals.ground_rhf
  return {
    about: 'Slim copy of docs/research/carbon-atom-data.json for the Carbon mode, written by scripts/research/carbon_slim.js. Energies in cm^-1 (E) and eV, tau in s, wavelengths in nm (Ritz, vacuum and standard air), A in s^-1, f the absorption oscillator strength, radii in bohr.',
    sources: Object.fromEntries(Object.entries(full.sources).map(([k, s]) => [k, s.cite || s.citation || k])),
    limit: full.ionization.limits['2P1/2'].energy_cm,
    limitEV: full.ionization.limits['2P1/2'].energy_eV,
    bohrNm: 0.0529177210544,
    levels,
    lines,
    rydberg: full.rydberg_draw_only.map(r => ({ series: r.series, n: r.n, E: r.energy_cm })),
    outer,
    rhf: {
      s: rhf.s_basis.map(b => [b.n, b.zeta, b.c1s, b.c2s]),
      p: rhf.p_basis.map(b => [b.n, b.zeta, b.c2p]),
      meanR: rhf.expect['<R>']
    }
  }
}

function render (data) {
  const body = JSON.stringify(data, null, 0)
    .replace(/\},\{/g, '},\n{')
    .replace(/\],"/g, '],\n"')
  return `'use strict'
// Generated by scripts/research/carbon_slim.js from
// docs/research/carbon-atom-data.json. Do not edit: run the script.
;(function (root) {
  const DATA = ${body}
  if (typeof module === 'object' && module.exports) module.exports = DATA
  else root.CarbonData = DATA
})(this)
`
}

const text = () => render(build(JSON.parse(fs.readFileSync(SRC, 'utf8'))))

if (require.main === module) {
  const t = text()
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === t
    console.log(same ? 'carbon-data.js matches' : 'carbon-data.js differs from the research data')
    process.exit(same ? 0 : 1)
  }
  fs.writeFileSync(OUT, t)
  console.log('wrote', path.relative(ROOT, OUT), t.length, 'bytes')
}

module.exports = { build, render, text, SRC, OUT }
