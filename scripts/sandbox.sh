# Chromium's sandbox for this checkout's Electron (decision 0001).
# Sourced by install.sh, bin/skinned and scripts/drive.js. Names start
# with sandbox_ or _sb_, since sh has no local variables.

SANDBOX_PROFILE=skindeep-electron
SANDBOX_PROFILE_FILE=/etc/apparmor.d/skindeep-electron

# sandbox_starts ELECTRON: true when Chromium's sandbox starts for
# ELECTRON. Electron sets it up before it prints its version, and aborts
# when it cannot, so --version is the probe. ulimit keeps the abort from
# writing a core, and the exit keeps the subshell from exec'ing Electron,
# so the shell that reports the signal is the one silenced here.
sandbox_starts() {
  (ulimit -c 0; "$1" --version; exit $?) >/dev/null 2>&1
}

# sandbox_route [RESTRICT [ENABLED]]: the root step that lets the
# sandbox start. apparmor where AppArmor is on and restricts
# unprivileged user namespaces (Ubuntu 23.10 and later), else setuid.
# The arguments name the two kernel files, for a test.
sandbox_route() {
  _sb_r=$(cat "${1:-/proc/sys/kernel/apparmor_restrict_unprivileged_userns}" 2>/dev/null) || _sb_r=
  _sb_e=$(cat "${2:-/sys/module/apparmor/parameters/enabled}" 2>/dev/null) || _sb_e=
  if [ "$_sb_r" = 1 ] && [ "$_sb_e" = Y ]; then echo apparmor; else echo setuid; fi
}

# sandbox_profile ELECTRON: the AppArmor profile that grants ELECTRON
# user namespaces, in the form of Ubuntu's own profile for Chrome.
# AppArmor attaches a profile by the path the kernel resolved, so
# ELECTRON must be absolute and free of links: the caller passes it
# through readlink -f. A path holding a character AppArmor reads as a
# glob, an escape or a quote is refused.
sandbox_profile() {
  case "$1" in
    /*) ;;
    *) echo "sandbox: $1 is not an absolute path" >&2; return 1 ;;
  esac
  case "$1" in
    *'"'*|*'\'*|*'*'*|*'?'*|*'['*|*']'*|*'{'*|*'}'*|*'^'*|*'
'*)
      echo "sandbox: AppArmor would read $1 as a pattern: move the checkout to a path without \" \\ * ? [ ] { } ^ or a newline" >&2
      return 1 ;;
  esac
  printf '%s\n' \
    "# generated by claude-skins install.sh for $1" \
    "# Chromium's sandbox needs user namespaces, which AppArmor restricts" \
    "# here. Unconfined otherwise, as Ubuntu's profile for Chrome." \
    'abi <abi/4.0>,' \
    'include <tunables/global>' \
    '' \
    "profile $SANDBOX_PROFILE \"$1\" flags=(unconfined) {" \
    '  userns,' \
    '}'
}

# The root-owned directory of the setuid helpers install.sh makes, and
# where apparmor_parser may live. Root runs only a parser from these
# system paths, never one the user's PATH names. Variables, for a test.
SANDBOX_HELPER_DIR=/usr/local/lib/claude-skins
SANDBOX_PARSERS='/usr/sbin/apparmor_parser /sbin/apparmor_parser'

# sandbox_helper ELECTRON: the root-owned copy of ELECTRON's setuid
# helper, one per Electron version, read from the version file beside
# ELECTRON. Root writes to this path, so a version that is not a plain
# version string fails.
sandbox_helper() {
  _sb_v=$(cat "$(dirname "$(readlink -f "$1")")/version" 2>/dev/null) || return 1
  case "$_sb_v" in
    ''|.*|*[!0-9A-Za-z.-]*) return 1 ;;
  esac
  printf '%s/electron-%s/chrome-sandbox\n' "$SANDBOX_HELPER_DIR" "$_sb_v"
}

# sandbox_env ELECTRON: export CHROME_DEVEL_SANDBOX as the root-owned
# helper, where install.sh made one. Chromium reads the variable only
# when no chrome-sandbox sits beside ELECTRON and the user owns
# ELECTRON.
sandbox_env() {
  _sb_h=$(sandbox_helper "$1") || return 0
  [ -f "$_sb_h" ] || return 0
  CHROME_DEVEL_SANDBOX=$_sb_h
  export CHROME_DEVEL_SANDBOX
}

# sandbox_q ARG: ARG quoted for sh, for a command printed to run.
sandbox_q() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

# sandbox_root SCRIPT ARGS...: sh -c SCRIPT with ARGS, as root by sudo,
# stdin passed through. sudo asks for a password only when SANDBOX_TTY
# is set, as install.sh sets it when its stdin is a terminal, so an
# install with no terminal fails instead of hanging. sudo reads the
# password from the terminal, never from stdin.
sandbox_root() {
  _sb_s=$1
  shift
  if sudo -n true 2>/dev/null; then sudo -n sh -c "$_sb_s" sh "$@"
  elif [ -n "${SANDBOX_TTY:-}" ]; then sudo sh -c "$_sb_s" sh "$@"
  else return 1
  fi
}

# sandbox_setuid ELECTRON: give Chromium its helper setuid root. Root
# never opens a path the user can write: the user reads chrome-sandbox
# beside ELECTRON and feeds it on stdin, and root installs it as
# sandbox_helper's root-owned 4755 copy, in a directory root owns. Then
# the user removes the helper beside ELECTRON, since Chromium takes the
# copy, by CHROME_DEVEL_SANDBOX, only in its absence. A copy already
# equal to the helper takes no root. A helper that is a link or not a
# regular file is refused. Where sudo fails, prints the command for
# root and fails.
sandbox_setuid() {
  _sb_src="$(dirname "$(readlink -f "$1")")/chrome-sandbox"
  _sb_dst=$(sandbox_helper "$1") || {
    echo "install: no plain Electron version beside $1" >&2
    return 1
  }
  if [ -L "$_sb_src" ] || { [ -e "$_sb_src" ] && [ ! -f "$_sb_src" ]; }; then
    echo "install: $_sb_src is a link or not a regular file, refused: remove $(dirname "$_sb_src") and run install.sh again, which downloads Electron again" >&2
    return 1
  fi
  if [ ! -e "$_sb_src" ]; then
    [ -f "$_sb_dst" ] && return 0
    echo "install: $_sb_src is missing: remove $(dirname "$_sb_src") and run install.sh again, which downloads Electron again" >&2
    return 1
  fi
  if ! cmp -s "$_sb_src" "$_sb_dst"; then
    echo "install: Chromium needs its helper setuid root here. With sudo, installing a copy of $_sb_src as $_sb_dst, root-owned 4755"
    _sb_step='install -d -o root -g root -m 755 "${1%/*}" && install -o root -g root -m 4755 /dev/stdin "$1"'
    if ! sandbox_root "$_sb_step" "$_sb_dst" < "$_sb_src"; then
      echo "install: the sandbox step needs root. Run this, then run install.sh again:" >&2
      echo "  sudo sh -c $(sandbox_q "$_sb_step") sh $(sandbox_q "$_sb_dst") < $(sandbox_q "$_sb_src")" >&2
      return 1
    fi
    cmp -s "$_sb_src" "$_sb_dst" || {
      echo "install: $_sb_dst differs from $_sb_src after the copy" >&2
      return 1
    }
  fi
  rm -f "$_sb_src"
}

# sandbox_apparmor ELECTRON: install and load the profile that grants
# ELECTRON user namespaces. The user writes the text and root receives
# it on stdin, so root reads no file the user can write, and runs the
# first apparmor_parser of SANDBOX_PARSERS. Where sudo fails, prints the
# command for root and fails.
sandbox_apparmor() {
  _sb_p=
  for _sb_c in $SANDBOX_PARSERS; do
    if [ -x "$_sb_c" ]; then _sb_p=$_sb_c; break; fi
  done
  [ -n "$_sb_p" ] || {
    echo "install: AppArmor restricts user namespaces here, but apparmor_parser is missing (package apparmor)" >&2
    return 1
  }
  _sb_t=$(sandbox_profile "$1") || return 1
  echo "install: AppArmor restricts user namespaces here. With sudo, installing the profile $SANDBOX_PROFILE_FILE that grants them to $1"
  _sb_step='install -m 644 /dev/stdin "$1" && "$2" -r "$1"'
  if ! printf '%s\n' "$_sb_t" | sandbox_root "$_sb_step" "$SANDBOX_PROFILE_FILE" "$_sb_p"; then
    echo "install: the sandbox step needs root. Run this, then run install.sh again:" >&2
    printf "  sudo sh -c %s sh %s %s <<'EOF'\n%s\nEOF\n" "$(sandbox_q "$_sb_step")" "$(sandbox_q "$SANDBOX_PROFILE_FILE")" "$(sandbox_q "$_sb_p")" "$_sb_t" >&2
    return 1
  fi
}
