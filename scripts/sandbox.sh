# Chromium's sandbox for this checkout's Electron (decision 0001).
# Sourced by install.sh, bin/skinned and scripts/drive.js. Names start
# with sandbox_ or _sb_, since sh has no local variables.

SANDBOX_PROFILE=skindeep-electron
SANDBOX_PROFILE_FILE=/etc/apparmor.d/skindeep-electron

# sandbox_starts ELECTRON: true when Chromium's sandbox starts for
# ELECTRON. Electron sets it up before it prints its version, and aborts
# when it cannot, so --version is the probe. ulimit keeps the abort from
# writing a core, and the exit keeps the subshell from exec'ing Electron,
# so the shell that reports the signal is the one silenced here.
sandbox_starts() {
  (ulimit -c 0; "$1" --version; exit $?) >/dev/null 2>&1
}

# sandbox_route [RESTRICT [ENABLED]]: the root step that lets the
# sandbox start. apparmor where AppArmor is on and restricts
# unprivileged user namespaces (Ubuntu 23.10 and later), else setuid.
# The arguments name the two kernel files, for a test.
sandbox_route() {
  _sb_r=$(cat "${1:-/proc/sys/kernel/apparmor_restrict_unprivileged_userns}" 2>/dev/null) || _sb_r=
  _sb_e=$(cat "${2:-/sys/module/apparmor/parameters/enabled}" 2>/dev/null) || _sb_e=
  if [ "$_sb_r" = 1 ] && [ "$_sb_e" = Y ]; then echo apparmor; else echo setuid; fi
}

# sandbox_profile ELECTRON: the AppArmor profile that grants ELECTRON
# user namespaces, in the form of Ubuntu's own profile for Chrome.
# AppArmor attaches a profile by the path the kernel resolved, so
# ELECTRON must be absolute and free of links: the caller passes it
# through readlink -f. A path holding a character AppArmor reads as a
# glob, an escape or a quote is refused.
sandbox_profile() {
  case "$1" in
    /*) ;;
    *) echo "sandbox: $1 is not an absolute path" >&2; return 1 ;;
  esac
  case "$1" in
    *'"'*|*'\'*|*'*'*|*'?'*|*'['*|*']'*|*'{'*|*'}'*|*'^'*|*'
'*)
      echo "sandbox: AppArmor would read $1 as a pattern: move the checkout to a path without \" \\ * ? [ ] { } ^ or a newline" >&2
      return 1 ;;
  esac
  printf '%s\n' \
    "# generated by claude-skins install.sh for $1" \
    "# Chromium's sandbox needs user namespaces, which AppArmor restricts" \
    "# here. Unconfined otherwise, as Ubuntu's profile for Chrome." \
    'abi <abi/4.0>,' \
    'include <tunables/global>' \
    '' \
    "profile $SANDBOX_PROFILE \"$1\" flags=(unconfined) {" \
    '  userns,' \
    '}'
}
