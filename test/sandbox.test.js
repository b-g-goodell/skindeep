'use strict'
// Chromium's sandbox (decision 0001): scripts/sandbox.sh's probe, route
// and AppArmor profile, and bin/skinned's refusal and its unsafe option,
// on a fake Electron in a temp checkout.
const test = require('node:test')
const assert = require('node:assert')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { spawnSync } = require('child_process')

const root = path.join(__dirname, '..')
const lib = path.join(root, 'scripts', 'sandbox.sh')
const tmpBase = process.env.XDG_RUNTIME_DIR || os.tmpdir()

// sh FUNCTION ARGS...: the function of scripts/sandbox.sh, run.
function sh (fn, ...args) {
  return spawnSync('sh', ['-c', `. "$0" && ${fn} "$@"`, lib, ...args], { encoding: 'utf8' })
}

function tmp (t, name) {
  const d = fs.mkdtempSync(path.join(tmpBase, `sandbox-${name}-`))
  t.after(() => fs.rmSync(d, { recursive: true, force: true }))
  return d
}

// A fake Electron: aborts as Chromium does unless --no-sandbox is given
// or FAKE_SANDBOX=ok, and records the arguments of a launch.
const FAKE = `#!/bin/sh
ok=$FAKE_SANDBOX
for a; do [ "$a" = --no-sandbox ] && ok=ok; done
[ "$ok" = ok ] || { echo 'FATAL: The SUID sandbox helper binary was found, but is not configured correctly.' >&2; exit 133; }
[ "$1" = --version ] && { echo v44.9.3; exit 0; }
printf '%s\\n' "$@" > "$FAKE_ARGS"
`

test('the route is apparmor only where AppArmor is on and restricts user namespaces', t => {
  const d = tmp(t, 'route')
  const f = (name, text) => { fs.writeFileSync(path.join(d, name), text); return path.join(d, name) }
  const r1 = f('r1', '1\n'); const r0 = f('r0', '0\n'); const y = f('y', 'Y\n'); const n = f('n', 'N\n')
  assert.strictEqual(sh('sandbox_route', r1, y).stdout, 'apparmor\n')
  assert.strictEqual(sh('sandbox_route', r0, y).stdout, 'setuid\n')
  assert.strictEqual(sh('sandbox_route', r1, n).stdout, 'setuid\n')
  assert.strictEqual(sh('sandbox_route', path.join(d, 'none'), y).stdout, 'setuid\n')
})

test('the profile grants user namespaces to the one path, quoted', () => {
  const r = sh('sandbox_profile', '/home/u/my repo/node_modules/electron/dist/electron')
  assert.strictEqual(r.status, 0)
  assert.strictEqual(r.stdout, [
    '# generated by claude-skins install.sh for /home/u/my repo/node_modules/electron/dist/electron',
    "# Chromium's sandbox needs user namespaces, which AppArmor restricts",
    "# here. Unconfined otherwise, as Ubuntu's profile for Chrome.",
    'abi <abi/4.0>,',
    'include <tunables/global>',
    '',
    'profile skindeep-electron "/home/u/my repo/node_modules/electron/dist/electron" flags=(unconfined) {',
    '  userns,',
    '}',
    ''
  ].join('\n'))
})

test('the profile parses, where apparmor_parser can check it without root', t => {
  const parser = ['/usr/sbin/apparmor_parser', '/sbin/apparmor_parser'].find(p => fs.existsSync(p))
  if (!parser || !fs.existsSync('/etc/apparmor.d/abi/4.0')) return t.skip('no AppArmor 4 parser')
  const d = tmp(t, 'parse')
  const file = path.join(d, 'profile')
  fs.writeFileSync(file, sh('sandbox_profile', '/home/u/a #b,c/electron').stdout)
  const r = spawnSync(parser, ['-Q', '-K', file], { encoding: 'utf8' })
  assert.strictEqual(r.status, 0, r.stderr)
})

test('a relative path or one AppArmor reads as a pattern gets no profile', () => {
  for (const p of ['rel/electron', '/a/*/electron', '/a/b?/electron', '/a/[x]/electron', '/a/{x}/electron', '/a/"x/electron', '/a/\\x/electron', '/a/^x/electron', '/a/x\ny/electron']) {
    const r = sh('sandbox_profile', p)
    assert.notStrictEqual(r.status, 0, p)
    assert.strictEqual(r.stdout, '', p)
  }
})

test('the probe follows Electron: false when it aborts, true when the sandbox starts', t => {
  const d = tmp(t, 'probe')
  const e = path.join(d, 'electron')
  fs.writeFileSync(e, FAKE, { mode: 0o755 })
  assert.notStrictEqual(spawnSync('sh', ['-c', `. "$0" && sandbox_starts "$1"`, lib, e]).status, 0)
  assert.strictEqual(spawnSync('sh', ['-c', `. "$0" && sandbox_starts "$1"`, lib, e], { env: { ...process.env, FAKE_SANDBOX: 'ok' } }).status, 0)
})

// The real Electron in a user namespace bwrap made, where Chromium's
// namespace sandbox starts without root: the probe's true answer on the
// real binary. Skipped where bwrap cannot make one.
test('the probe is true for the real Electron where user namespaces work', t => {
  if (spawnSync('bwrap', ['--dev-bind', '/', '/', '--unshare-user', 'unshare', '-Ur', 'true']).status !== 0) return t.skip('bwrap cannot nest a user namespace here')
  let electron
  try { electron = require('electron') } catch (e) { return t.skip('Electron not downloaded') }
  const r = spawnSync('bwrap', ['--dev-bind', '/', '/', '--unshare-user', 'sh', '-c', `. "$0" && sandbox_starts "$1"`, lib, electron])
  assert.strictEqual(r.status, 0)
})

// A temp checkout with bin/skinned, scripts/sandbox.sh and the fake.
function checkout (t) {
  const d = tmp(t, 'skinned')
  fs.mkdirSync(path.join(d, 'repo', 'bin'), { recursive: true })
  fs.mkdirSync(path.join(d, 'repo', 'scripts'))
  fs.mkdirSync(path.join(d, 'repo', 'node_modules', 'electron', 'dist'), { recursive: true })
  fs.copyFileSync(path.join(root, 'bin', 'skinned'), path.join(d, 'repo', 'bin', 'skinned'))
  fs.chmodSync(path.join(d, 'repo', 'bin', 'skinned'), 0o755)
  fs.copyFileSync(lib, path.join(d, 'repo', 'scripts', 'sandbox.sh'))
  fs.writeFileSync(path.join(d, 'repo', 'node_modules', 'electron', 'dist', 'electron'), FAKE, { mode: 0o755 })
  const args = path.join(d, 'args')
  const run = (argv, env = {}) => {
    fs.rmSync(args, { force: true })
    const r = spawnSync(path.join(d, 'repo', 'bin', 'skinned'), argv, {
      encoding: 'utf8',
      env: { PATH: process.env.PATH, HOME: d, XDG_STATE_HOME: path.join(d, 'state'), XDG_RUNTIME_DIR: d, FAKE_ARGS: args, ...env }
    })
    return { status: r.status, stderr: r.stderr, args: fs.existsSync(args) ? fs.readFileSync(args, 'utf8').split('\n').slice(0, -1) : null }
  }
  return { repo: path.join(d, 'repo'), run }
}

test('bin/skinned refuses where the sandbox cannot start, naming install.sh and the option', t => {
  const { repo, run } = checkout(t)
  const r = run(['--', 'true'])
  assert.strictEqual(r.status, 125)
  assert.strictEqual(r.args, null, 'no launch')
  assert.match(r.stderr, /Chromium's sandbox does not start/)
  assert.ok(r.stderr.includes(`run ${repo}/install.sh once`), r.stderr)
  assert.match(r.stderr, /--unsafe-no-sandbox or SKINNED_UNSAFE_NO_SANDBOX=1/)
})

test('bin/skinned runs unsandboxed only when asked by option or variable', t => {
  const { repo, run } = checkout(t)
  for (const [argv, env] of [[['--unsafe-no-sandbox', '--mute', '--', 'true'], {}], [['--mute', '--', 'true'], { SKINNED_UNSAFE_NO_SANDBOX: '1' }]]) {
    const r = run(argv, env)
    assert.strictEqual(r.status, 0, r.stderr)
    assert.strictEqual(r.args[0], '--no-sandbox')
    assert.strictEqual(r.args[1], repo)
    assert.ok(r.args.includes('--mute') && r.args.slice(-2).join(' ') === '-- true', r.args.join(' '))
  }
  assert.strictEqual(run(['--', 'true'], { SKINNED_UNSAFE_NO_SANDBOX: '0' }).status, 125)
})

test('bin/skinned keeps the sandbox where it starts', t => {
  const { repo, run } = checkout(t)
  const r = run(['--', 'true'], { FAKE_SANDBOX: 'ok' })
  assert.strictEqual(r.status, 0, r.stderr)
  assert.deepStrictEqual(r.args, [repo, '--', 'true'])
})

// The root steps of install.sh, sandbox_setuid and sandbox_apparmor, on
// a fake dist and a fake sudo. The sudo records each call's arguments
// and stdin, then runs the call as the user, through an install that
// drops -o and -g, which need root. FAKE_SUDO=deny makes it refuse.
const FAKE_SUDO = `#!/bin/sh
[ "$FAKE_SUDO" = deny ] && exit 1
[ "$1" = -n ] && shift
[ "$*" = true ] && exit 0
n=$(ls "$REC" | wc -l)
printf '%s\\n' "$@" > "$REC/$n.argv"
cat > "$REC/$n.stdin"
"$@" < "$REC/$n.stdin"
`
const FAKE_INSTALL = `#!/bin/sh
skip=
for a; do
  shift
  [ -z "$skip" ] || { skip=; continue; }
  case $a in -o|-g) skip=1; continue ;; esac
  set -- "$@" "$a"
done
exec /usr/bin/install "$@"
`

function rootSteps (t) {
  const d = tmp(t, 'root')
  const dist = path.join(d, 'electron', 'dist')
  const fake = path.join(d, 'fakebin')
  const rec = path.join(d, 'rec')
  for (const x of [dist, fake, rec]) fs.mkdirSync(x, { recursive: true })
  fs.writeFileSync(path.join(dist, 'electron'), FAKE, { mode: 0o755 })
  fs.writeFileSync(path.join(dist, 'version'), '44.9.3')
  fs.writeFileSync(path.join(fake, 'sudo'), FAKE_SUDO, { mode: 0o755 })
  fs.writeFileSync(path.join(fake, 'install'), FAKE_INSTALL, { mode: 0o755 })
  const helperDir = path.join(d, 'root')
  // run FUNCTION [ENV]: the function on this dist, with the test's
  // helper directory, profile file and parsers.
  const run = (fn, env = {}, parsers = path.join(d, 'parser')) => spawnSync('sh', ['-c',
    `. "$0" && SANDBOX_HELPER_DIR="$1" SANDBOX_PROFILE_FILE="$2" SANDBOX_PARSERS="$3" && ${fn} "$4"`,
    lib, helperDir, path.join(d, 'profile'), parsers, path.join(dist, 'electron')], {
    encoding: 'utf8',
    env: { PATH: `${fake}:${process.env.PATH}`, REC: rec, SANDBOX_TTY: '', ...env }
  })
  const calls = () => fs.readdirSync(rec).filter(f => f.endsWith('.argv')).sort().map(f => ({
    argv: fs.readFileSync(path.join(rec, f), 'utf8').split('\n').slice(0, -1),
    stdin: fs.readFileSync(path.join(rec, f.replace('.argv', '.stdin')))
  }))
  return { d, dist, helperDir, run, calls, helper: path.join(dist, 'chrome-sandbox'), dest: path.join(helperDir, 'electron-44.9.3', 'chrome-sandbox') }
}

test('the root-owned helper is named by the Electron version, which must be plain', t => {
  const { dist, helperDir, run } = rootSteps(t)
  assert.strictEqual(run('sandbox_helper').stdout, `${helperDir}/electron-44.9.3/chrome-sandbox\n`)
  for (const v of ['../../../usr/bin', '44.9.3/x', '', '.', '44 9']) {
    fs.writeFileSync(path.join(dist, 'version'), v)
    const r = run('sandbox_helper')
    assert.notStrictEqual(r.status, 0, v)
    assert.strictEqual(r.stdout, '', v)
  }
})

test('sandbox_env exports CHROME_DEVEL_SANDBOX only where the root-owned helper exists', t => {
  const { dest, run } = rootSteps(t)
  const show = 'sandbox_env "$4" && printf %s "${CHROME_DEVEL_SANDBOX-unset}" && :'
  assert.strictEqual(run(show).stdout, 'unset')
  fs.mkdirSync(path.dirname(dest), { recursive: true })
  fs.writeFileSync(dest, 'x')
  assert.strictEqual(run(show).stdout, dest)
})

test('the setuid step feeds the helper to one root shell, which installs a 4755 copy in its own directory', t => {
  const { helper, dest, run, calls } = rootSteps(t)
  const bytes = Buffer.from('\x7fELF helper bytes\n')
  fs.writeFileSync(helper, bytes, { mode: 0o755 })
  const r = run('sandbox_setuid')
  assert.strictEqual(r.status, 0, r.stderr)
  const c = calls()
  assert.strictEqual(c.length, 1)
  assert.deepStrictEqual(c[0].argv, ['sh', '-c', 'install -d -o root -g root -m 755 "${1%/*}" && install -o root -g root -m 4755 /dev/stdin "$1"', 'sh', dest])
  assert.deepStrictEqual(c[0].stdin, bytes)
  assert.deepStrictEqual(fs.readFileSync(dest), bytes)
  assert.strictEqual(fs.statSync(dest).mode & 0o7777, 0o4755)
  assert.ok(!fs.existsSync(helper), 'the helper beside Electron is removed')
  // A later download puts the same helper back: no root, removed again.
  fs.writeFileSync(helper, bytes, { mode: 0o755 })
  assert.strictEqual(run('sandbox_setuid').status, 0)
  assert.strictEqual(calls().length, 1)
  assert.ok(!fs.existsSync(helper))
})

test('the setuid step refuses a symlinked helper, and root is never called', t => {
  const { d, helper, run, calls } = rootSteps(t)
  const victim = path.join(d, 'victim')
  fs.writeFileSync(victim, 'victim', { mode: 0o755 })
  fs.symlinkSync(victim, helper)
  const r = run('sandbox_setuid')
  assert.notStrictEqual(r.status, 0)
  assert.match(r.stderr, /is a link or not a regular file, refused/)
  assert.strictEqual(calls().length, 0)
  assert.strictEqual(fs.statSync(victim).mode & 0o7777, 0o755)
  assert.strictEqual(fs.readlinkSync(helper), victim)
  fs.unlinkSync(helper)
  fs.mkdirSync(helper)
  assert.notStrictEqual(run('sandbox_setuid').status, 0, 'a directory is refused too')
  assert.strictEqual(calls().length, 0)
})

test('without sudo the setuid step prints the one command for root, fed on stdin', t => {
  const { helper, dest, run, calls } = rootSteps(t)
  fs.writeFileSync(helper, 'h', { mode: 0o755 })
  const r = run('sandbox_setuid', { FAKE_SUDO: 'deny' })
  assert.notStrictEqual(r.status, 0)
  assert.strictEqual(calls().length, 0)
  assert.ok(r.stderr.includes(`  sudo sh -c 'install -d -o root -g root -m 755 "\${1%/*}" && install -o root -g root -m 4755 /dev/stdin "$1"' sh '${dest}' < '${helper}'\n`), r.stderr)
  assert.ok(fs.existsSync(helper), 'the helper stays until root has its copy')
})

test('the AppArmor step feeds the profile to one root shell and runs the parser of a system path', t => {
  const { d, dist, run, calls } = rootSteps(t)
  const parser = path.join(d, 'parser')
  fs.writeFileSync(parser, '#!/bin/sh\nprintf "%s\\n" "$@" > "$REC/parser"\n', { mode: 0o755 })
  const r = run('sandbox_apparmor')
  assert.strictEqual(r.status, 0, r.stderr)
  const text = sh('sandbox_profile', path.join(dist, 'electron')).stdout
  const c = calls()
  assert.strictEqual(c.length, 1)
  assert.deepStrictEqual(c[0].argv, ['sh', '-c', 'install -m 644 /dev/stdin "$1" && "$2" -r "$1"', 'sh', path.join(d, 'profile'), parser])
  assert.strictEqual(c[0].stdin.toString(), text)
  assert.strictEqual(fs.readFileSync(path.join(d, 'profile'), 'utf8'), text)
  assert.strictEqual(fs.readFileSync(path.join(d, 'rec', 'parser'), 'utf8'), `-r\n${path.join(d, 'profile')}\n`)
  assert.deepStrictEqual(fs.readdirSync(dist).sort(), ['electron', 'version'], 'nothing staged beside Electron')
})

test('the AppArmor step never takes apparmor_parser from PATH', t => {
  const { d, run, calls } = rootSteps(t)
  fs.writeFileSync(path.join(d, 'fakebin', 'apparmor_parser'), '#!/bin/sh\nexit 0\n', { mode: 0o755 })
  const r = run('sandbox_apparmor', {}, path.join(d, 'none'))
  assert.notStrictEqual(r.status, 0)
  assert.match(r.stderr, /apparmor_parser is missing/)
  assert.strictEqual(calls().length, 0)
})
