#!/bin/sh
# Remove the commands install.sh wrote: every file in BINDIR (default
# ~/.local/bin) whose second line is the installer's marker. The
# checkout and its node_modules stay.
set -eu

bin="${BINDIR:-$HOME/.local/bin}"
marker='# generated by claude-skins install.sh'

for f in "$bin"/*; do
  [ -f "$f" ] || continue
  if [ "$(sed -n '2{p;q}' "$f")" = "$marker" ]; then
    rm -f "$f"
    echo "uninstall: removed $f"
  fi
done
